/**
 * Refreshes the shadcn/ui components that ship in the "Web app (shadcn/ui)"
 * export: node scripts/update-shadcn.mjs
 *
 * Fetches the components below (and the ones they use) from the shadcn
 * registry (style new-york-v4), rewrites their imports for a normal project
 * (@/lib/utils, @/components/ui/…) and writes
 * app/assets/js/data/shadcnComponents.js. The export reads that file, so it
 * works offline and every export ships the same code.
 *
 * shadcn/ui is MIT licensed (c) 2023 shadcn.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const STYLE = 'new-york-v4';
const BASE = `https://ui.shadcn.com/r/styles/${STYLE}/`;
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'assets', 'js', 'data', 'shadcnComponents.js');

const WANT = [
    'accordion', 'alert', 'alert-dialog', 'avatar', 'badge', 'breadcrumb', 'button', 'card', 'checkbox', 'command',
    'dialog', 'dropdown-menu', 'field', 'input', 'input-group', 'kbd', 'label', 'pagination', 'popover', 'radio-group',
    'scroll-area', 'select', 'separator', 'sheet', 'skeleton', 'slider', 'spinner', 'switch', 'table', 'tabs',
    'textarea', 'toggle', 'toggle-group', 'tooltip'
];

const items = new Map();

async function get(name) {
    if (items.has(name)) return;
    items.set(name, null);
    const response = await fetch(`${BASE}${name}.json`);
    if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
    const item = await response.json();
    if (item.type !== 'registry:ui') throw new Error(`${name}: not a UI component (${item.type})`);
    items.set(name, item);
    for (const dep of item.registryDependencies || []) await get(dep.replace(/^.*\//, '').replace(/\.json$/, ''));
}

const rewrite = (code) => code
    .replace(/from "cn"/g, 'from "@/lib/utils"')
    .replace(/@\/registry\/[\w-]+\/ui\//g, '@/components/ui/')
    .replace(/@\/registry\/[\w-]+\/lib\//g, '@/lib/')
    .replace(/@\/registry\/[\w-]+\/hooks\//g, '@/hooks/');

for (const name of WANT) await get(name);

const components = {};
const packages = new Set();
for (const [name, item] of [...items].sort(([a], [b]) => a.localeCompare(b))) {
    if (item.files.length !== 1) throw new Error(`${name}: expected one file, got ${item.files.length}`);
    const code = rewrite(item.files[0].content);
    const left = code.match(/from "@\/registry[^"]*"/);
    if (left) throw new Error(`${name}: import not rewritten: ${left[0]}`);
    components[name] = code;
    for (const m of code.matchAll(/from "([^".][^"]*)"/g)) {
        const spec = m[1];
        if (spec.startsWith('@/') || spec === 'react') continue;
        packages.add(spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]);
    }
}

const date = new Date().toISOString().slice(0, 10);
const out = `/* Generated by scripts/update-shadcn.mjs on ${date}. Do not edit by hand.
   shadcn/ui components, style ${STYLE}, from the shadcn registry.
   shadcn/ui: MIT License, Copyright (c) 2023 shadcn. https://github.com/shadcn-ui/ui */

export const SHADCN_STYLE = ${JSON.stringify(STYLE)};

/** npm packages the components import (besides react). */
export const SHADCN_PACKAGES = ${JSON.stringify([...packages].sort())};

/** name → src/components/ui/<name>.tsx */
export const SHADCN_COMPONENTS = ${JSON.stringify(components, null, 1)};
`;
fs.writeFileSync(OUT, out);
console.log(`${Object.keys(components).length} components, packages: ${[...packages].sort().join(', ')}\n→ ${OUT} (${Math.round(out.length / 1024)} KB)`);
